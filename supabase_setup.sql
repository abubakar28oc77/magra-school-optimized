-- 1. Real-time Multi-Device Cloud Sync Store (Mobile <-> Laptop <-> Tablet)
CREATE TABLE IF NOT EXISTS public.app_sync_store (
    key TEXT PRIMARY KEY,
    value JSONB NOT NULL,
    updated_at TIMESTAMPTZ DEFAULT NOW()
);

ALTER TABLE public.app_sync_store ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS Allow public all on app_sync_store ON public.app_sync_store;
CREATE POLICY Allow public all on app_sync_store ON public.app_sync_store FOR ALL USING (true) WITH CHECK (true);

-- 2. Teachers Table
CREATE TABLE IF NOT EXISTS public.teachers (
    id TEXT PRIMARY KEY,
    employee_id TEXT UNIQUE,
    name_bn TEXT NOT NULL,
    name_en TEXT,
    designation TEXT,
    designation_en TEXT,
    subject TEXT,
    phone TEXT,
    email TEXT,
    gender TEXT,
    address TEXT,
    photo_url TEXT,
    status TEXT DEFAULT 'active',
    joining_date TEXT,
    public_contact_role TEXT,
    public_contact_enabled BOOLEAN DEFAULT true,
    mpo_index_no TEXT,
    teacher_registration_no TEXT,
    nid_no TEXT,
    extended_profile JSONB DEFAULT '{}'::jsonb,
    created_at TIMESTAMPTZ DEFAULT NOW(),
    updated_at TIMESTAMPTZ DEFAULT NOW()
);
ALTER TABLE public.teachers ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS Allow public all on teachers ON public.teachers;
CREATE POLICY Allow public all on teachers ON public.teachers FOR ALL USING (true) WITH CHECK (true);

